//! Small, fail-closed PTX frontend. No instruction or directive is silently erased.
use std::collections::{BTreeMap, BTreeSet};

#[derive(Debug, PartialEq, Eq)]
struct Token {
    text: String,
    line: usize,
}

fn lex(src: &str) -> Result<Vec<Token>, String> {
    let bytes = src.as_bytes();
    let (mut i, mut line) = (0, 1);
    let mut out = Vec::new();
    while i < bytes.len() {
        let b = bytes[i];
        if b == b'\n' {
            line += 1;
            i += 1;
            continue;
        }
        if b.is_ascii_whitespace() {
            i += 1;
            continue;
        }
        if bytes[i..].starts_with(b"//") {
            while i < bytes.len() && bytes[i] != b'\n' {
                i += 1;
            }
            continue;
        }
        if bytes[i..].starts_with(b"/*") {
            i += 2;
            while i < bytes.len() && !bytes[i..].starts_with(b"*/") {
                if bytes[i] == b'\n' {
                    line += 1;
                }
                i += 1;
            }
            if i == bytes.len() {
                return Err(format!("line {line}: unterminated comment"));
            }
            i += 2;
            continue;
        }
        if b"{}()[],;:@!+<>".contains(&b) {
            out.push(Token {
                text: (b as char).to_string(),
                line,
            });
            i += 1;
            continue;
        }
        let start = i;
        while i < bytes.len() && (bytes[i].is_ascii_alphanumeric() || b"._%$".contains(&bytes[i])) {
            i += 1;
        }
        if i == start {
            return Err(format!(
                "line {line}: unsupported character {:?}",
                b as char
            ));
        }
        out.push(Token {
            text: src[start..i].to_owned(),
            line,
        });
    }
    Ok(out)
}

#[derive(Debug)]
pub struct Program {
    name: String,
    pub code: Vec<String>,
    lines: Vec<usize>,
    shared_bytes: usize,
    params: BTreeMap<String, usize>,
}

impl Program {
    pub fn emit(&self) -> String {
        let code = self
            .code
            .iter()
            .zip(&self.lines)
            .map(|(i, l)| format!("  {i}, -- PTX line {l}\n"))
            .collect::<String>();
        let params = self
            .params
            .iter()
            .map(|(n, w)| format!("({}, {w})", quote(n)))
            .collect::<Vec<_>>()
            .join(", ");
        format!(
            "-- Generated by ptx-verify; program DATA only. No per-kernel semantics.\nimport Ptx.Semantics\nnamespace Ptx.Generated.«{}»\ndef kernelName : String := {}\ndef sharedBytes : Nat := {}\ndef parameters : List (String × Nat) := [{}]\ndef program : List Instr := [\n{}]\nend Ptx.Generated.«{}»\n",
            self.name,
            quote(&self.name),
            self.shared_bytes,
            params,
            code,
            self.name
        )
    }
}

fn quote(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

struct Parser {
    tokens: Vec<Token>,
    pos: usize,
    regs: BTreeMap<String, String>,
    params: BTreeMap<String, usize>,
    shared: BTreeMap<String, usize>,
    shared_bytes: usize,
}
impl Parser {
    fn peek(&self) -> &str {
        self.tokens
            .get(self.pos)
            .map_or("<eof>", |t| t.text.as_str())
    }
    fn err(&self, s: impl AsRef<str>) -> String {
        format!(
            "line {}: {} (at {})",
            self.tokens.get(self.pos).map_or(0, |t| t.line),
            s.as_ref(),
            self.peek()
        )
    }
    fn take(&mut self) -> Result<String, String> {
        let t = self
            .tokens
            .get(self.pos)
            .ok_or_else(|| self.err("unexpected end"))?;
        self.pos += 1;
        Ok(t.text.clone())
    }
    fn expect(&mut self, s: &str) -> Result<(), String> {
        if self.peek() != s {
            return Err(self.err(format!("expected {s}")));
        }
        self.pos += 1;
        Ok(())
    }
    fn number(&mut self) -> Result<usize, String> {
        let s = self.take()?;
        let n = if let Some(h) = s.strip_prefix("0x") {
            usize::from_str_radix(h, 16)
        } else {
            s.parse()
        };
        n.map_err(|_| self.err(format!("expected unsigned integer, got {s}")))
    }
    fn ident(&mut self) -> Result<String, String> {
        let s = self.take()?;
        if !s
            .bytes()
            .next()
            .is_some_and(|b| b.is_ascii_alphabetic() || b == b'_')
            || !s
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b"_$".contains(&b))
        {
            return Err(self.err("expected identifier"));
        }
        Ok(s)
    }
    fn reg(&mut self, types: &[&str]) -> Result<String, String> {
        let r = self.take()?;
        if !self
            .regs
            .get(&r)
            .is_some_and(|t| types.contains(&t.as_str()))
        {
            return Err(self.err(format!("undeclared or incorrectly typed register {r}")));
        }
        Ok(quote(&r))
    }
    fn operand(&mut self, width: usize) -> Result<String, String> {
        if self.peek() == "%tid.x" {
            if width != 32 {
                return Err(self.err("%tid.x is a 32-bit special register"));
            }
            self.pos += 1;
            return Ok(".tid".into());
        }
        if self.peek().starts_with('%') {
            let types = if width == 32 {
                vec![".u32", ".b32"]
            } else {
                vec![".u64", ".b64"]
            };
            return Ok(format!("(.reg {})", self.reg(&types)?));
        }
        if let Some(base) = self.shared.get(self.peek()).copied() {
            self.pos += 1;
            return Ok(format!("(.imm {base})"));
        }
        let n = self.number()?;
        if width == 32 && n > u32::MAX as usize {
            return Err(self.err("u32 immediate out of range"));
        }
        Ok(format!("(.imm {n})"))
    }
    fn address(&mut self) -> Result<String, String> {
        self.expect("[")?;
        let base = self.operand(64)?;
        let offset = if self.peek() == "+" {
            self.pos += 1;
            self.number()?
        } else {
            0
        };
        self.expect("]")?;
        Ok(format!("{{ base := {base}, offset := {offset} }}"))
    }
    fn declaration(&mut self) -> Result<(), String> {
        match self.take()?.as_str() {
            ".reg" => {
                let ty = self.take()?;
                if ![".u32", ".u64", ".b32", ".b64", ".pred"].contains(&ty.as_str()) {
                    return Err(self.err("unsupported register type"));
                }
                let prefix = self.take()?;
                let Some(body) = prefix.strip_prefix('%') else {
                    return Err(self.err("invalid register declaration"));
                };
                if !body
                    .bytes()
                    .next()
                    .is_some_and(|b| b.is_ascii_alphabetic() || b == b'_')
                    || !body
                        .bytes()
                        .all(|b| b.is_ascii_alphanumeric() || b"_$".contains(&b))
                {
                    return Err(self.err("invalid register declaration"));
                }
                let names = if self.peek() == "<" {
                    self.pos += 1;
                    let n = self.number()?;
                    self.expect(">")?;
                    if n == 0 || n > 4096 {
                        return Err(self.err("register array count must be 1..4096"));
                    }
                    (0..n).map(|i| format!("{prefix}{i}")).collect()
                } else {
                    vec![prefix]
                };
                self.expect(";")?;
                for n in names {
                    if self.regs.insert(n, ty.clone()).is_some() {
                        return Err(self.err("duplicate register"));
                    }
                }
            }
            ".shared" => {
                self.expect(".align")?;
                let align = self.number()?;
                if align != 4 {
                    return Err(self.err("only .shared .align 4 .b8 arrays supported"));
                }
                self.expect(".b8")?;
                let name = self.ident()?;
                self.expect("[")?;
                let size = self.number()?;
                self.expect("]")?;
                self.expect(";")?;
                if size == 0 || size % 4 != 0 {
                    return Err(self.err("shared size must be positive and divisible by 4"));
                }
                if self.shared.insert(name, self.shared_bytes).is_some() {
                    return Err(self.err("duplicate shared symbol"));
                }
                self.shared_bytes = self
                    .shared_bytes
                    .checked_add(size)
                    .ok_or_else(|| self.err("shared size overflow"))?;
            }
            _ => return Err(self.err("unsupported declaration")),
        }
        Ok(())
    }
    fn instruction(&mut self, labels: &BTreeMap<String, usize>) -> Result<String, String> {
        let pred = if self.peek() == "@" {
            self.pos += 1;
            let positive = if self.peek() == "!" {
                self.pos += 1;
                false
            } else {
                true
            };
            let r = self.reg(&[".pred"])?;
            Some((r, positive))
        } else {
            None
        };
        let op = self.take()?;
        if pred.is_some() && op != "bra" {
            return Err(self.err("only branches may be predicated in this subset"));
        }
        let instr = match op.as_str() {
            "ret" => ".ret".into(),
            "bar.sync" => {
                let id = self.number()?;
                if id > 15 {
                    return Err(self.err("barrier ID must be 0..15"));
                }
                format!("(.barrier {id})")
            }
            "bra" => {
                let label = self.ident()?;
                let pc = labels
                    .get(&label)
                    .ok_or_else(|| self.err(format!("unknown label {label}")))?;
                if let Some((r, b)) = pred {
                    format!("(.branch {r} {b} {pc})")
                } else {
                    format!("(.jump {pc})")
                }
            }
            "ld.param.u64" | "ld.param.u32" => {
                let w = if op.ends_with("64") { 64 } else { 32 };
                let r = self.reg(if w == 64 {
                    &[".u64", ".b64"]
                } else {
                    &[".u32", ".b32"]
                })?;
                self.expect(",")?;
                self.expect("[")?;
                let p = self.ident()?;
                self.expect("]")?;
                if self.params.get(&p) != Some(&w) {
                    return Err(self.err("unknown or incorrectly typed parameter"));
                }
                format!("(.param {w} {r} {})", quote(&p))
            }
            "mov.u32" | "mov.u64" => {
                let w = if op.ends_with("64") { 64 } else { 32 };
                let r = self.reg(if w == 64 {
                    &[".u64", ".b64"]
                } else {
                    &[".u32", ".b32"]
                })?;
                self.expect(",")?;
                let a = self.operand(w)?;
                format!("(.mov {w} {r} {a})")
            }
            "add.u32" | "add.u64" | "sub.u32" | "sub.u64" | "mul.lo.u32" | "mul.lo.u64"
            | "mul.wide.u32" => {
                let w = if op.ends_with("64") { 64 } else { 32 };
                let out_w = if op == "mul.wide.u32" { 64 } else { w };
                let r = self.reg(if out_w == 64 {
                    &[".u64", ".b64"]
                } else {
                    &[".u32", ".b32"]
                })?;
                self.expect(",")?;
                let a = self.operand(w)?;
                self.expect(",")?;
                let b = self.operand(w)?;
                let operator = if op.starts_with("add") {
                    "add"
                } else if op.starts_with("sub") {
                    "sub"
                } else {
                    "mul"
                };
                format!("(.bin .{operator} {w} {out_w} {r} {a} {b})")
            }
            "setp.lt.u32" | "setp.ge.u32" | "setp.eq.u32" => {
                let r = self.reg(&[".pred"])?;
                self.expect(",")?;
                let a = self.operand(32)?;
                self.expect(",")?;
                let b = self.operand(32)?;
                let cmp = op.split('.').nth(1).unwrap();
                format!("(.setp .{cmp} {r} {a} {b})")
            }
            "ld.global.u32" | "ld.shared.u32" => {
                let r = self.reg(&[".u32", ".b32"])?;
                self.expect(",")?;
                let a = self.address()?;
                let space = if op.contains("global") {
                    "global"
                } else {
                    "shared"
                };
                format!("(.load .{space} {r} {a})")
            }
            "st.global.u32" | "st.shared.u32" => {
                let a = self.address()?;
                self.expect(",")?;
                let v = self.operand(32)?;
                let space = if op.contains("global") {
                    "global"
                } else {
                    "shared"
                };
                format!("(.store .{space} {a} {v})")
            }
            _ => return Err(self.err(format!("unsupported instruction {op}"))),
        };
        self.expect(";")?;
        Ok(instr)
    }
}

pub fn parse(src: &str) -> Result<Program, String> {
    let mut p = Parser {
        tokens: lex(src)?,
        pos: 0,
        regs: BTreeMap::new(),
        params: BTreeMap::new(),
        shared: BTreeMap::new(),
        shared_bytes: 0,
    };
    p.expect(".version")?;
    let version = p.take()?;
    if version != "7.0" {
        return Err(p.err("only PTX .version 7.0 currently supported"));
    }
    p.expect(".target")?;
    p.expect("sm_70")?;
    p.expect(".address_size")?;
    p.expect("64")?;
    if p.peek() == ".visible" {
        p.pos += 1;
    }
    p.expect(".entry")?;
    let name = p.ident()?;
    p.expect("(")?;
    while p.peek() != ")" {
        p.expect(".param")?;
        let ty = p.take()?;
        let width = match ty.as_str() {
            ".u64" => 64,
            ".u32" => 32,
            _ => return Err(p.err("unsupported parameter type")),
        };
        let n = p.ident()?;
        if p.params.insert(n, width).is_some() {
            return Err(p.err("duplicate parameter"));
        }
        if p.peek() != ")" {
            p.expect(",")?;
            if p.peek() == ")" {
                return Err(p.err("trailing parameter comma"));
            }
        }
    }
    p.expect(")")?;
    p.expect("{")?;
    while p.peek().starts_with('.') {
        p.declaration()?;
    }
    // First pass records instruction boundaries/label PCs; second pass typechecks instructions.
    let start = p.pos;
    let mut labels = BTreeMap::new();
    let mut starts = Vec::new();
    while p.peek() != "}" {
        if p.pos + 1 < p.tokens.len() && p.tokens[p.pos + 1].text == ":" {
            let n = p.ident()?;
            p.expect(":")?;
            if labels.insert(n, starts.len()).is_some() {
                return Err(p.err("duplicate label"));
            }
        } else {
            starts.push(p.pos);
            while p.peek() != ";" {
                if matches!(p.peek(), "<eof>" | "}") {
                    return Err(p.err("missing semicolon"));
                }
                p.pos += 1;
            }
            p.pos += 1;
        }
    }
    let end = p.pos;
    p.expect("}")?;
    if p.pos != p.tokens.len() {
        return Err(p.err("multiple entries or trailing input unsupported"));
    }
    if starts.is_empty() {
        return Err(p.err("empty kernel"));
    }
    let valid_pcs: BTreeSet<usize> = (0..starts.len()).collect();
    if labels.values().any(|pc| !valid_pcs.contains(pc)) {
        return Err(p.err("label points past end of kernel"));
    }
    let mut code = Vec::new();
    let mut lines = Vec::new();
    p.pos = start;
    for s in starts {
        p.pos = s;
        lines.push(p.tokens[s].line);
        code.push(p.instruction(&labels)?);
        if p.pos > end {
            return Err(p.err("instruction crosses kernel boundary"));
        }
    }
    Ok(Program {
        name,
        code,
        lines,
        shared_bytes: p.shared_bytes,
        params: p.params,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    fn wrap(s: &str) -> String {
        format!(
            ".version 7.0\n.target sm_70\n.address_size 64\n.visible .entry k() {{ .reg .u32 %r<2>; .reg .pred %p; {s} }}"
        )
    }
    #[test]
    fn branches_resolve_instruction_pcs() {
        let p = parse(&wrap(
            "L: add.u32 %r0,%r0,1; setp.lt.u32 %p,%r0,8; @%p bra L; ret;",
        ))
        .unwrap();
        assert_eq!(p.code[2], "(.branch \"%p\" true 0)");
    }
    #[test]
    fn fail_closed() {
        for s in [
            "atom.global.add.u32 %r0,[%r1],1;",
            "@%p ret;",
            "bra missing;",
            "mov.u64 %r0,1;",
            "mov.u32 %x,1;",
            "bar.sync 0,32;",
            "ret; unknown;",
        ] {
            assert!(parse(&wrap(s)).is_err(), "{s}");
        }
    }
    #[test]
    fn malformed_and_trailing_input() {
        for s in [
            wrap("ret"),
            format!("{} .entry other() {{ ret; }}", wrap("ret;")),
            wrap("mov.u32 %r0,4294967296;"),
            wrap("/* unclosed"),
            wrap("L: ret; L: ret;"),
        ] {
            assert!(parse(&s).is_err(), "{s}");
        }
    }
    #[test]
    fn rejects_unmodeled_address_conversion_and_bad_declarations() {
        for s in [
            ".reg .u64 %d; cvta.to.global.u64 %d, %d; ret;",
            ".reg .u64 %d; mov.u64 %d, %tid.x; ret;",
            ".reg .u32 %zero<0>; ret;",
            ".reg .u32 %; ret;",
        ] {
            assert!(parse(&wrap(s)).is_err(), "{s}");
        }
    }
    #[test]
    fn comments_and_whitespace_preserve_program() {
        let a = parse(&wrap("mov.u32 %r0, %tid.x; ret;")).unwrap();
        let b = parse(&wrap("/*x*/mov.u32/*y*/%r0,\n%tid.x;// tail\nret;")).unwrap();
        assert_eq!(a.code, b.code);
    }
}
